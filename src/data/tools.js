export function getFileFormat(url) {
  if (!url) return null;
  const u = url.toLowerCase();
  if (u.includes('.rar') || u.includes('rar/file')) return 'RAR';
  if (u.includes('.zip') || u.includes('zip/file')) return 'ZIP';
  if (u.includes('.exe')) return 'EXE';
  if (u.includes('.7z')) return '7Z';
  if (u.includes('github.com')) return 'GitHub';
  if (u.includes('mega.nz')) return 'MEGA';
  if (u.includes('drive.google.com')) return 'GDrive';
  if (u.includes('pastebin.com')) return 'Pastebin';
  if (u.startsWith('http')) return 'Web';
  return null;
}

